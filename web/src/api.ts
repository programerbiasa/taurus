import axios from 'axios';

// Base API URL menggunakan proxy Vite atau direct host
export const API_BASE_URL = import.meta.env.VITE_API_URL || '/api';

const api = axios.create({
  baseURL: API_BASE_URL,
  headers: {
    'Content-Type': 'application/json',
  },
});

// Request Interceptor: Sisipkan JWT Token jika ada
api.interceptors.request.use(
  (config) => {
    const token = localStorage.getItem('taurus_token');
    if (token && config.headers) {
      config.headers.Authorization = `Bearer ${token}`;
    }
    return config;
  },
  (error) => Promise.reject(error)
);

// Response Interceptor: Tangani error 401 (Unauthorized)
api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response && error.response.status === 401) {
      // Jika token invalid/expired, bersihkan session & arahkan ke login
      localStorage.removeItem('taurus_token');
      localStorage.removeItem('taurus_user');
      if (window.location.pathname !== '/login') {
        window.location.href = '/login';
      }
    }
    return Promise.reject(error);
  }
);

export default api;
